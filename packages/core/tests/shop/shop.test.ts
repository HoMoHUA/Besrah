// Shopping: honest snapshot semantics over the real imported catalog and over synthetic edge cases.
import { existsSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { buildServer } from '../../src/server.js';
import { SHOP_CATALOG_URL, loadShopCatalog, parseShopCatalog, searchShop, shopProduct } from '../../src/shop/search.js';

const NOW = Date.parse('2026-11-04T16:00:00Z');
const offer = (seller: string, price: number | null, state: 'resolved' | 'unresolved' | 'quarantined' = 'resolved', extra: Record<string, unknown> = {}) => ({
  seller, merchant: 'تکنولایف', url: 'https://www.technolife.com/product-1/', matchState: 'listing_declared', variantUnresolved: ['رنگ', 'گارانتی'], stock: 'unknown', availabilityDeclared: 'InStock', shipping: 'unknown', state, priceToman: price, ...extra });
const product = (sku: string, title: string, offers: ReturnType<typeof offer>[], observedAt = '2026-11-04T10:00:00Z') => {
  const prices = offers.filter(o => o.state === 'resolved').map(o => o.priceToman!);
  return { canonicalProductId: `tl:${sku}`, sku, title, brand: null, category: 'دسته', variantBasis: 'x', observedAt, source: { kind: 'technolife_product_page_jsonld', url: `https://www.technolife.com/product-${sku}/` }, offers,
    summary: { resolved: prices.length, minToman: prices.length ? Math.min(...prices) : null, maxToman: prices.length ? Math.max(...prices) : null } };
};
const fixture = () => parseShopCatalog(JSON.stringify({ v: 1, generatedAt: '2026-11-04T10:00:00Z', licenseNote: 'x', products: [
  product('1', 'هدفون بلوتوثی سونی مدل ایکس', [offer('الف', 1_300_000), offer('ب', 1_400_000), offer('ج', 1_000_000), offer('د', 90_000, 'quarantined', { reason: 'outlier_vs_median' })]),
  product('2', 'پاوربانک شیائومی', [offer('الف', 600_000)]),
  product('3', 'اسپیکر جی بی ال', [offer('الف', null, 'unresolved', { priceCandidatesToman: [2_000_000, 2_100_000], reason: 'same_seller_multiple_prices' })]),
  product('4', 'قدیمی', [offer('الف', 500_000), offer('ب', 510_000)], '2026-10-30T10:00:00Z'),
] }));

describe('searchShop', () => {
  const c = fixture();
  it('matches Persian text across letter variants and AND-s the words', () => {
    expect(searchShop(c, { q: 'هدفون سوني' }, NOW).products.map(p => p.id)).toEqual(['tl:1']);
    expect(searchShop(c, { q: 'هدفون پاوربانک' }, NOW).total).toBe(0);
    expect(searchShop(c, {}, NOW).total).toBe(4);
  });
  it('labels price states without inventing a price for unresolved products', () => {
    const r = searchShop(c, {}, NOW).products;
    expect(r.find(p => p.id === 'tl:1')).toMatchObject({ priceState: 'compared', minToman: 1_000_000, maxToman: 1_400_000, resolvedOffers: 3, offerCount: 4 });
    expect(r.find(p => p.id === 'tl:2')?.priceState).toBe('single_offer');
    expect(r.find(p => p.id === 'tl:3')).toMatchObject({ priceState: 'unresolved', minToman: null });
  });
  it('a budget keeps only products with a resolved price at or under it; unresolved never pass', () => {
    expect(searchShop(c, { maxPrice: 700_000 }, NOW).products.map(p => p.id)).toEqual(['tl:2', 'tl:4']);
    expect(searchShop(c, { maxPrice: 5_000_000 }, NOW).products.map(p => p.id)).not.toContain('tl:3');
  });
  it('price sort puts unresolved last and the snapshot reports age from the oldest observation', () => {
    const r = searchShop(c, { sort: 'price' }, NOW);
    expect(r.products.at(-1)?.id).toBe('tl:3');
    expect(r.snapshot).toMatchObject({ observedFrom: '2026-10-30T10:00:00.000Z', stale: true });
    expect(r.notes.join(' ')).toMatch(/ارزان ترین بودن در بازار ادعا نمی شود/);
  });
});

describe('shopProduct', () => {
  const c = fixture();
  it('lists resolved offers by price, then unresolved, then quarantined; spread comes only from resolved ones', () => {
    const p = shopProduct(c, 'tl:1', NOW)!;
    expect(p.offers.map(o => `${o.seller}:${o.state}`)).toEqual(['ج:resolved', 'الف:resolved', 'ب:resolved', 'د:quarantined']);
    expect(p.offers.at(-1)).toMatchObject({ priceToman: null, reason: 'outlier_vs_median' });
    expect(p.spread).toEqual({ minToman: 1_000_000, maxToman: 1_400_000, ratio: 1.4 });
  });
  it('keeps stock and shipping unknown and exposes the unresolved candidates instead of one chosen price', () => {
    const p = shopProduct(c, 'tl:3', NOW)!;
    expect(p.offers[0]).toMatchObject({ state: 'unresolved', priceToman: null, priceCandidatesToman: [2_000_000, 2_100_000], stock: 'unknown', shipping: 'unknown' });
    expect(p.spread).toBeNull();
    expect(shopProduct(c, 'tl:9', NOW)).toBeNull();
  });
});

// data/shop/catalog-v1.json is generated by scripts/shop/import_offers.py and is not committed to the public repository.
describe.skipIf(!existsSync(SHOP_CATALOG_URL))('real catalog', () => {
  const real = existsSync(SHOP_CATALOG_URL) ? loadShopCatalog() : (null as never);
  it('every product has provenance, a timestamp, IRR-converted prices and no invented offer', () => {
    expect(real.products.length).toBeGreaterThanOrEqual(8);
    for (const { raw } of real.products) {
      expect(raw.source.url).toMatch(/^https:\/\/www\.technolife\.com\/product-\d+\//);
      expect(Date.parse(raw.observedAt)).toBeGreaterThan(Date.parse('2026-11-01T00:00:00Z'));
      for (const o of raw.offers) {
        expect(o.stock).toBe('unknown'); expect(o.shipping).toBe('unknown'); expect(o.matchState).toBe('listing_declared');
        if (o.state === 'resolved') { expect(Number.isInteger(o.priceToman)).toBe(true); expect(o.priceToman!).toBeGreaterThan(10_000); } else expect(o.priceToman).toBeNull();
      }
    }
    expect(real.products.filter(p => p.raw.summary.resolved >= 2).length).toBeGreaterThanOrEqual(6);
  });
});

describe('routes', () => {
  const make = (opts: Parameters<typeof buildServer>[0] = {}) => buildServer({ now: () => NOW, shop: { catalog: fixture() }, ...opts });
  it('search and product answer with validation', async () => {
    const app = make();
    const s = (await app.inject({ url: '/app/api/shop/search?q=%D9%87%D8%AF%D9%81%D9%88%D9%86&maxPrice=2000000' })).json();
    expect(s.total).toBe(1);
    expect((await app.inject({ url: '/app/api/shop/product?id=tl:1' })).json().offers).toHaveLength(4);
    expect((await app.inject({ url: '/app/api/shop/product?id=tl:99' })).statusCode).toBe(404);
    for (const bad of ['/app/api/shop/search?maxPrice=abc', '/app/api/shop/search?sort=cheapest', '/app/api/shop/search?x=1', '/app/api/shop/search?limit=99', '/app/api/shop/product?id=../x', '/app/api/shop/product']) {
      expect((await app.inject({ url: bad })).statusCode, bad).toBe(400);
    }
    await app.close();
  });
  it('a missing or corrupt catalog answers 503 for shopping only and leaves the metro alone', async () => {
    const app = make({ shop: { loader: () => { throw new Error('missing'); } } });
    expect((await app.inject({ url: '/app/api/shop/search' })).statusCode).toBe(503);
    expect((await app.inject({ url: '/app/api/stations' })).statusCode).toBe(200);
    await app.close();
  });
});
